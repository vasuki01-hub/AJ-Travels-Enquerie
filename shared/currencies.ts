/**
 * Look up a currency by its ISO 4217 code.
 */
export function getCurrencyByCode(code: string): CurrencyInfo | undefined {
  return CURRENCIES.find((c) => c.code === code.toUpperCase());
}

/**
 * Return the display symbol for a currency code, falling back to the code itself.
 */
export function getCurrencySymbol(code: string): string {
  return getCurrencyByCode(code)?.symbol ?? code;
}
